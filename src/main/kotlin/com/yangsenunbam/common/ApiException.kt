package com.yangsenunbam.common

import com.fasterxml.jackson.annotation.JsonInclude

enum class ErrorCode(val status: Int) {
    MALFORMED_JSON(400), UNAUTHORIZED(401), INVALID_CREDENTIALS(401), INVALID_REFRESH_TOKEN(401),
    ONBOARDING_REQUIRED(403), ADMIN_REQUIRED(403), RESOURCE_NOT_FOUND(404), METHOD_NOT_ALLOWED(405),
    EMAIL_ALREADY_USED(409), CONSENT_VERSION_CHANGED(409), BIRTH_DATE_EDIT_LIMIT(409), NIGHT_CLOSED(409),
    WORRY_ALREADY_RECORDED(409), SUPPORT_REQUIRED(409), ACTIVE_SESSION_EXISTS(409), SESSION_CLOSED(409),
    WRITER_REPLACED(409), SEQUENCE_CONFLICT(409), PAUSE_ALREADY_HANDLED(409), FINISH_CONFLICT(409),
    CLOSING_NOT_AVAILABLE(409), CARD_UNAVAILABLE(409), OFFER_ALREADY_DECIDED(409), OFFER_NOT_AVAILABLE(409),
    MORNING_NOT_OPEN(409), NO_ADOPTION_CANDIDATE(409), ADOPTION_ALREADY_FINALIZED(409),
    REFLECTION_NOT_AVAILABLE(409), DAY_ONLY(409), VERSION_CONFLICT(409), WRITING_ENTRY_REQUIRED(409),
    CARD_NOT_REJECTED(409), MODERATION_CONFLICT(409), IDEMPOTENCY_CONFLICT(409), REQUEST_IN_PROGRESS(409),
    UNSUPPORTED_MEDIA_TYPE(415), VALIDATION_ERROR(422), INVALID_RESET_TOKEN(422), AGE_NOT_ALLOWED(422),
    INVALID_PAUSE_ITEM(422), INVALID_FINISH_POSITION(422), CARD_NOT_VIEWED(422), NOT_SONG_CARD(422),
    INVALID_ADOPTION_CARD(422), SUPPORT_RECOMMENDED(422), TRACK_NOT_FOUND(422), RATE_LIMITED(429),
    INTERNAL_ERROR(500), NOT_IMPLEMENTED(501), SAFETY_CHECK_UNAVAILABLE(503), FEED_BUILD_UNAVAILABLE(503),
    FORTUNE_UNAVAILABLE(503), MUSIC_SEARCH_UNAVAILABLE(503)
}

class ApiException(
    val code: ErrorCode,
    override val message: String,
    val fields: Map<String, String> = emptyMap(),
    val support: SupportResponse? = null,
) : RuntimeException(message)

data class ErrorResponse(val error: ErrorDetail)
data class ErrorDetail(
    val code: String,
    val message: String,
    val fields: Map<String, String>,
    val requestId: String,
    @get:JsonInclude(JsonInclude.Include.NON_NULL) val support: SupportResponse? = null,
)

fun notImplemented(): Nothing = throw ApiException(ErrorCode.NOT_IMPLEMENTED, "아직 구현되지 않은 기능입니다.")
